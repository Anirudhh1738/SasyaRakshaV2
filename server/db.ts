export class DatabaseNotConfiguredError extends Error {
  constructor() {
    super('PostgreSQL DATABASE_URL is not configured. Add DATABASE_URL to your environment variables.');
    this.name = 'DatabaseNotConfiguredError';
  }
}

function getConnectionString(): string {
  return (process.env.DATABASE_URL || '').trim();
}

export function isDatabaseConfigured(): boolean {
  return Boolean(getConnectionString());
}

function shouldUseSsl(connStr: string): boolean {
  if (process.env.DATABASE_SSL === 'false') return false;
  if (process.env.DATABASE_SSL === 'true') return true;
  const lower = connStr.toLowerCase();
  if (lower.includes('localhost') || lower.includes('127.0.0.1')) {
    return lower.includes('sslmode=require');
  }
  return (
    process.env.NODE_ENV === 'production' ||
    lower.includes('supabase.com') ||
    lower.includes('supabase.co') ||
    lower.includes('sslmode=require') ||
    lower.includes('render.com')
  );
}

let pool: pg.Pool | null = null;

export function getPool(): pg.Pool {
  const connStr = getConnectionString();
  if (!connStr) {
    throw new DatabaseNotConfiguredError();
  }
  if (!pool) {
    pool = new Pool({
      connectionString: connStr,
      ssl: shouldUseSsl(connStr) ? { rejectUnauthorized: false } : undefined,
      max: Number(process.env.PG_POOL_MAX || 10),
      idleTimeoutMillis: 30000,
      connectionTimeoutMillis: 10000,
    });
    pool.on('error', (err) => {
      console.error('Unexpected PostgreSQL pool error:', err.message);
    });
  }
  return pool;
}

export async function closePool(): Promise<void> {
  if (pool) {
    const p = pool;
    pool = null;
    await p.end();
  }
}

export async function query<T extends pg.QueryResultRow = Record<string, unknown>>(
  sql: string,
  params: unknown[] = []
): Promise<T[]> {
  const result = await getPool().query<T>(sql, params);
  return result.rows;
}

export async function queryOne<T extends pg.QueryResultRow = Record<string, unknown>>(
  sql: string,
  params: unknown[] = []
): Promise<T | undefined> {
  const result = await getPool().query<T>(sql, params);
  return result.rows[0];
}

export async function execute(sql: string, params: unknown[] = []): Promise<pg.QueryResult> {
  return getPool().query(sql, params);
}

export async function withTransaction<T>(fn: (client: pg.PoolClient) => Promise<T>): Promise<T> {
  const client = await getPool().connect();
  try {
    await client.query('BEGIN');
    const result = await fn(client);
    await client.query('COMMIT');
    return result;
  } catch (err) {
    try {
      await client.query('ROLLBACK');
    } catch {
      // ignore rollback errors
    }
    throw err;
  } finally {
    client.release();
  }
}

export async function checkDatabaseHealth(): Promise<{
  configured: boolean;
  connected: boolean;
  engine: 'postgresql';
  error?: string;
}> {
  if (!isDatabaseConfigured()) {
    return {
      configured: false,
      connected: false,
      engine: 'postgresql',
      error: 'DATABASE_URL environment variable not set',
    };
  }
  try {
    await getPool().query('SELECT 1');
    return { configured: true, connected: true, engine: 'postgresql' };
  } catch (err) {
    return {
      configured: true,
      connected: false,
      engine: 'postgresql',
      error: err instanceof Error ? err.message : 'Database connection failed',
    };
  }
}

