export async function createDatabaseBackup(): Promise<{
  filename: string;
  fullPath: string;
  sizeBytes: number;
  createdAt: string;
}> {
  if (!fs.existsSync(BACKUPS_DIR)) {
    fs.mkdirSync(BACKUPS_DIR, { recursive: true });
  }
  const stamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
  const filename = `sasyaraksha_pg_snapshot_${stamp}.json`;
  const fullPath = path.join(BACKUPS_DIR, filename);

  const tables = [
    'plants',
    'weather_records',
    'predictions',
    'screening_images',
    'soil_records',
    'uploaded_images',
    'severity_analyses',
    'field_passports',
    'geographical_reports',
    'disease_library',
    'treatment_records',
    'progression_entries',
    'expert_corrections',
    'audit_logs',
    'model_evaluations',
  ];

  const payload: Record<string, unknown> = {
    exportedAt: new Date().toISOString(),
    engine: 'postgresql',
    users: await query(
      'SELECT id, name, email, role, region, preferred_language, is_active, created_at FROM users ORDER BY id ASC'
    ),
  };

  for (const tbl of tables) {
    payload[tbl] = await query(`SELECT * FROM ${tbl} ORDER BY id ASC`);
  }

  const serialized = JSON.stringify(payload, null, 2);
  fs.writeFileSync(fullPath, serialized, 'utf-8');
  const stat = fs.statSync(fullPath);

  return {
    filename,
    fullPath,
    sizeBytes: stat.size,
    createdAt: new Date().toISOString(),
  };
}

export function listDatabaseBackups(): Array<{ filename: string; sizeBytes: number; createdAt: string }> {
  if (!fs.existsSync(BACKUPS_DIR)) return [];
  return fs
    .readdirSync(BACKUPS_DIR)
    .filter((f) => f.endsWith('.json'))
    .map((f) => {
      const stat = fs.statSync(path.join(BACKUPS_DIR, f));
      return {
        filename: f,
        sizeBytes: stat.size,
        createdAt: stat.mtime.toISOString(),
      };
    })
    .sort((a, b) => b.createdAt.localeCompare(a.createdAt));
}
