const { Pool, types } = pg;

// Preserve numeric counts (INT8 / OID 20) as JS numbers for safe arithmetic & UI rendering
types.setTypeParser(20, (val: string) => Number(val));

// Format TIMESTAMP (1114) and TIMESTAMPTZ (1184) consistently as 'YYYY-MM-DD HH:MM:SS' UTC strings
// so frontend .slice(0, 10) / .slice(0, 16) and Date parsing behave identically to the previous API contract.
function formatPgTimestamp(val: string): string {
  if (!val) return '';
  const d = new Date(val);
  if (Number.isNaN(d.getTime())) return String(val).slice(0, 19);
  return d.toISOString().replace('T', ' ').slice(0, 19);
}
types.setTypeParser(1114, formatPgTimestamp);
types.setTypeParser(1184, formatPgTimestamp);

